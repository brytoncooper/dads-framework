use dads_testing_core::{
    NativeRequest, Operation, PROTOCOL_SCHEMA_VERSION, execute_request_with_graph,
};
use dads_testing_javascript::analyze_workspace_graph;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

struct TempWorkspace(PathBuf);

impl TempWorkspace {
    fn new(label: &str) -> Result<Self, Box<dyn Error>> {
        static COUNTER: AtomicUsize = AtomicUsize::new(0);
        let id = COUNTER.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "dads-ext-bare-{label}-{}-{id}",
            std::process::id()
        ));
        if dir.exists() {
            fs::remove_dir_all(&dir)?;
        }
        fs::create_dir_all(&dir)?;
        Ok(Self(dir))
    }

    fn write(&self, rel: &str, content: &str) -> Result<(), Box<dyn Error>> {
        let full = self.0.join(rel);
        if let Some(parent) = full.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(full, content)?;
        Ok(())
    }

    fn git(&self, args: &[&str]) -> Result<(), Box<dyn Error>> {
        let status = Command::new("git")
            .args(args)
            .current_dir(&self.0)
            .output()?;
        if !status.status.success() {
            return Err(format!(
                "git {:?} failed: {}",
                args,
                String::from_utf8_lossy(&status.stderr)
            )
            .into());
        }
        Ok(())
    }
}

impl Drop for TempWorkspace {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn manifest_json() -> &'static str {
    r#"{
  "schemaVersion": 1,
  "workspace": {
    "root": ".",
    "fullFallback": { "taskIds": ["lib:test", "app:test"] }
  },
  "projects": [
    { "id": "lib", "root": "libs/lib", "fallbackDependencies": [] },
    { "id": "app", "root": "apps/app", "fallbackDependencies": ["lib"] }
  ],
  "tasks": [
    {
      "id": "lib:test",
      "project": "lib",
      "kind": "test",
      "execution": { "executable": "node", "args": ["-e", "0"], "cwd": "." },
      "dependsOn": [],
      "impact": { "mode": "reachability", "paths": [] }
    },
    {
      "id": "app:test",
      "project": "app",
      "kind": "test",
      "execution": { "executable": "node", "args": ["-e", "0"], "cwd": "." },
      "dependsOn": [],
      "impact": { "mode": "reachability", "paths": [] }
    }
  ]
}"#
}

fn plan_for_workspace(root: &Path) -> Result<dads_testing_core::PlanResult, Box<dyn Error>> {
    let graph = analyze_workspace_graph(root, None);
    let response = execute_request_with_graph(
        NativeRequest {
            schema_version: PROTOCOL_SCHEMA_VERSION,
            operation: Operation::Plan,
            workspace_root: root.to_string_lossy().into_owned(),
            ..NativeRequest::default()
        },
        Some(graph),
    );
    response
        .result
        .map(|r| r.plan)
        .ok_or_else(|| format!("plan failed: {:?}", response.error).into())
}

#[test]
fn declared_external_packages_resolve_without_node_modules_and_do_not_widen()
-> Result<(), Box<dyn Error>> {
    let ws = TempWorkspace::new("declared-ext")?;
    ws.git(&["init", "-q"])?;
    ws.git(&["config", "user.email", "test@example.com"])?;
    ws.git(&["config", "user.name", "Test"])?;
    ws.write("dads.testing.json", manifest_json())?;
    ws.write(
        "package.json",
        r#"{
  "name": "monorepo-root",
  "dependencies": { "zod": "^3.23.0", "@tanstack/react-query": "^5.0.0" },
  "devDependencies": { "vitest": "^3.0.0" }
}"#,
    )?;
    ws.write(
        "libs/lib/src/index.ts",
        "import { z } from 'zod';\nimport { useQuery } from '@tanstack/react-query/subpath';\nexport const used = () => z.string();\nexport const unused = () => useQuery;\n",
    )?;
    ws.write(
        "apps/app/src/app.test.ts",
        "import { describe } from 'vitest';\nimport { used } from '../../../libs/lib/src/index';\nexport const run = () => [describe, used()];\n",
    )?;
    ws.git(&["add", "-A"])?;
    ws.git(&["commit", "-q", "-m", "baseline"])?;

    // Edit only `unused` in lib — with declared external packages recognized without node_modules,
    // `app:test` must NOT widen via `graph-uncertainty-project-fallback`.
    ws.write(
        "libs/lib/src/index.ts",
        "import { z } from 'zod';\nimport { useQuery } from '@tanstack/react-query/subpath';\nexport const used = () => z.string();\nexport const unused = () => [useQuery, 2];\n",
    )?;

    let graph = analyze_workspace_graph(&ws.0, None);
    let bare_uncertainties: Vec<_> = graph
        .uncertainties()
        .into_iter()
        .filter(|u| u.code == "unresolved-bare-module")
        .collect();
    assert!(
        bare_uncertainties.is_empty(),
        "declared external packages must not emit unresolved-bare-module: {bare_uncertainties:?}"
    );

    let plan = plan_for_workspace(&ws.0)?;
    let app_task = plan
        .tasks
        .iter()
        .find(|t| t.id == "app:test")
        .ok_or("missing app:test")?;
    assert_eq!(app_task.decision, "skip-proven-unaffected");
    Ok(())
}

#[test]
fn undeclared_workspace_linked_and_tsconfig_alias_bare_imports_still_fail_closed()
-> Result<(), Box<dyn Error>> {
    let ws = TempWorkspace::new("fail-closed")?;
    ws.write(
        "package.json",
        r#"{
  "name": "root",
  "dependencies": {
    "zod": "^3.23.0",
    "local-linked": "workspace:*",
    "@myorg/shared": "^1.0.0",
    "@alias/pkg": "^1.0.0"
  }
}"#,
    )?;
    ws.write("libs/shared/package.json", r#"{ "name": "@myorg/shared" }"#)?;
    ws.write(
        "tsconfig.json",
        r#"{
  // JSONC comment should be handled cleanly
  "compilerOptions": {
    "paths": { "@alias/*": ["libs/alias/*"] }
  }
}"#,
    )?;
    ws.write(
        "src/entry.ts",
        "import 'zod';\nimport 'totally-undeclared';\nimport 'local-linked';\nimport '@myorg/shared';\nimport '@alias/pkg';\n",
    )?;

    let graph = analyze_workspace_graph(&ws.0, None);
    let messages: Vec<String> = graph
        .uncertainties()
        .into_iter()
        .filter(|u| u.code == "unresolved-bare-module")
        .map(|u| u.message)
        .collect();

    assert!(
        !messages.iter().any(|m| m.contains("zod")),
        "zod is declared external and must not emit unresolved-bare-module: {messages:?}"
    );
    assert!(
        messages.iter().any(|m| m.contains("totally-undeclared")),
        "undeclared package must fail closed: {messages:?}"
    );
    assert!(
        messages.iter().any(|m| m.contains("local-linked")),
        "workspace:* linked package must fail closed: {messages:?}"
    );
    assert!(
        messages.iter().any(|m| m.contains("@myorg/shared")),
        "workspace package name must fail closed: {messages:?}"
    );
    assert!(
        messages.iter().any(|m| m.contains("@alias/pkg")),
        "tsconfig paths alias must fail closed: {messages:?}"
    );
    Ok(())
}
