import { describe, expect, it } from "vitest";
import { z } from "zod";

import {
  access,
  accessIrDefinitionsDiff,
  accessModel,
  actor,
  allOf,
  anyOf,
  both,
  compileAccess,
  emitAccessIr,
  emitTypeScript,
  emitZed,
  entityHandle,
  every,
  excluding,
  isPermissionToken,
  isRoleToken,
  membersOf,
  parseZed,
  resource,
  throughAll,
  wildcard,
  withExpiration,
  type ActorRef,
  type DslResource,
  type ResourceSubjectRef,
} from "../index.js";

describe("ergonomic access DSL", () => {
  it("compiles top-down organization -> task -> photo, order, and fail-closed billing with exact Zed parity", () => {
    const user = actor("user");

    const organization = resource("organization", {
      roles: {
        admin: user,
        member: user,
      },
      can: ({ admin, member }) => ({
        manage: admin,
        edit: admin,
        view: [admin, member],
      }),
      children: {
        task: {
          inherit: "all",
          roles: {
            assignee: user,
          },
          can: ({ assignee }) => ({
            edit: assignee,
            comment: assignee,
          }),
          children: {
            photo: {
              inherit: "all",
            },
          },
        },
        order: {
          inherit: "none",
          roles: {
            buyer: user,
          },
          can: ({ buyer }) => ({
            view: buyer,
          }),
        },
        billing: {
          inherit: ["manage"],
          roles: {
            accountant: user,
          },
          can: ({ accountant }) => ({
            view: accountant,
          }),
        },
      },
    });

    expect(user("alice")).toEqual({
      kind: "actor-ref",
      type: "user",
      id: "alice",
    });
    expect(isPermissionToken(organization.task.can.edit)).toBe(true);
    expect(organization.task.can.edit).toBe(organization.task.permissions.edit);
    expect(isRoleToken(organization.task.roles.organization)).toBe(true);
    expect(organization.task("t1").organization).toEqual({
      kind: "dsl-role-slot",
      entityWireName: "task",
      roleName: "organization",
      resource: { type: "task", id: "t1" },
    });
    expect(organization.task("t1").edit).toEqual({
      kind: "dsl-permission-target",
      entityWireName: "task",
      permissionName: "edit",
      resource: { type: "task", id: "t1" },
    });

    const model = compileAccess([organization]);
    const zed = emitZed(model);

    expect(zed).toBe(
      [
        "// GENERATED by the access kit — do not edit",
        "",
        "definition user {}",
        "",
        "definition organization {",
        "  relation admin: user",
        "  relation member: user",
        "",
        "  permission manage = admin",
        "  permission edit = admin",
        "  permission view = admin + member",
        "}",
        "",
        "definition task {",
        "  relation organization: organization",
        "  relation assignee: user",
        "",
        "  permission manage = organization->manage",
        "  permission edit = organization->edit + assignee",
        "  permission view = organization->view",
        "  permission comment = assignee",
        "}",
        "",
        "definition photo {",
        "  relation task: task",
        "",
        "  permission manage = task->manage",
        "  permission edit = task->edit",
        "  permission view = task->view",
        "  permission comment = task->comment",
        "}",
        "",
        "definition order {",
        "  relation organization: organization",
        "  relation buyer: user",
        "",
        "  permission view = buyer",
        "}",
        "",
        "definition billing {",
        "  relation organization: organization",
        "  relation accountant: user",
        "",
        "  permission manage = organization->manage",
        "  permission view = accountant",
        "}",
        "",
      ].join("\n"),
    );

    // Fail-closed proof: billing has ONLY manage and view, never edit.
    const billingDef = model.definitions.find(
      (def) => def.entity.wireName === "billing",
    );
    expect(Object.keys(billingDef?.expressions ?? {})).toEqual([
      "manage",
      "view",
    ]);

    // Round-trip through parseZed + emitTypeScript compatibility.
    expect(accessIrDefinitionsDiff(emitAccessIr(model), parseZed(zed))).toEqual(
      [],
    );
    expect(emitTypeScript(emitAccessIr(model))).toContain(
      "export const access = compileAccess(",
    );
    expect(emitTypeScript(emitAccessIr(model), { style: "classic" })).toContain(
      "export const model",
    );
  });

  it("supports splitting child resources across separate variables via .child()", () => {
    const user = actor("user");

    const organization = resource("organization", {
      roles: { admin: user, member: user },
      can: ({ admin, member }) => ({
        manage: admin,
        view: [admin, member],
      }),
    });

    const project = organization.child("project", {
      inherit: "all",
      roles: { lead: user, blocked: user },
      can: ({ lead, blocked, parent }) => ({
        manage: parent.manage.or(lead).unless(blocked),
      }),
    });

    const milestone = project.child("milestone", {
      inherit: ["view"],
      roles: { owner: user },
      can: ({ owner }) => ({
        close: owner,
      }),
    });

    // compileAccess([organization]) auto-discovers .child(...) branches too.
    const model = compileAccess([organization]);
    const zed = emitZed(model);

    expect(zed).toContain(
      "permission manage = (organization->manage + lead) - (blocked)",
    );
    expect(zed).toContain("definition milestone {");
    expect(zed).toContain("relation project: project");
    expect(zed).toContain("permission view = project->view");
    expect(zed).toContain("permission close = owner");
    expect(milestone.can.view.entityWireName).toBe("milestone");
    expect(accessIrDefinitionsDiff(emitAccessIr(model), parseZed(zed))).toEqual(
      [],
    );
  });

  it("wires recursive: true self-inheritance for top-level and child folders", () => {
    const user = actor("user");

    const folder = resource("folder", {
      recursive: true,
      roles: { editor: user, viewer: user },
      can: ({ editor, viewer }) => ({
        edit: editor,
        view: [editor, viewer],
      }),
    });

    const workspace = resource("workspace", {
      roles: { admin: user },
      can: ({ admin }) => ({ view: admin }),
    });
    const nestedFolder = workspace.child("nested_folder", {
      inherit: "all",
      recursive: true,
      roles: { contributor: user },
      can: ({ contributor }) => ({ edit: contributor }),
    });

    const model = compileAccess([folder, workspace]);
    const zed = emitZed(model);

    expect(zed).toContain("relation parent: folder");
    expect(zed).toContain("permission edit = editor + parent->edit");
    expect(zed).toContain("permission view = editor + viewer + parent->view");

    expect(zed).toContain("definition nested_folder {");
    expect(zed).toContain("relation workspace: workspace");
    expect(zed).toContain("relation parent: nested_folder");
    expect(zed).toContain("permission view = workspace->view + parent->view");
    expect(zed).toContain("permission edit = contributor + parent->edit");
    expect(nestedFolder("nf1").parent.roleName).toBe("parent");
    expect(nestedFolder("nf1").workspace.roleName).toBe("workspace");
    expect(accessIrDefinitionsDiff(emitAccessIr(model), parseZed(zed))).toEqual(
      [],
    );
  });

  it("compiles multi-parent DAG resources with parents: [organization, folder]", () => {
    const user = actor("user");

    const organization = resource("organization", {
      roles: { admin: user, member: user },
      can: ({ admin, member }) => ({
        manage: admin,
        edit: admin,
        view: [admin, member],
      }),
    });

    const folder = resource("folder", {
      recursive: true,
      roles: { editor: user, viewer: user },
      can: ({ editor, viewer }) => ({
        edit: editor,
        view: [editor, viewer],
      }),
    });

    const document = resource("document", {
      parents: [organization, folder],
      roles: { author: user },
      can: ({ author, parents }) => ({
        edit: [author, parents.edit],
        view: [author, parents.view],
      }),
    });

    // Auto-discovers organization, folder, and user from document alone!
    const model = compileAccess([document]);
    const zed = emitZed(model);

    expect(zed).toContain("definition organization {");
    expect(zed).toContain("definition folder {");
    expect(zed).toContain("relation parent: organization | folder");
    expect(zed).toContain("permission edit = author + parent->edit");
    expect(zed).toContain("permission view = author + parent->view");
    expect(accessIrDefinitionsDiff(emitAccessIr(model), parseZed(zed))).toEqual(
      [],
    );
  });

  it("compiles every(), expiring, anyone, userset roles, combinators, and matches manual access() IR", () => {
    const user = actor("user");

    const team = resource("team", {
      roles: { member: user },
      can: ({ member }) => ({ view: member }),
    });

    const reviewGroup = resource("review_group", {
      roles: { reviewer: user },
      can: ({ reviewer }) => ({
        view: reviewer,
        approve: reviewer,
      }),
    });

    const doc = resource("doc", {
      roles: {
        owner: user,
        guest: user.expiring,
        public_link: user.anyone,
        team_viewer: team.roles.member,
        review_group: reviewGroup,
        active: user.anyone,
        banned: user,
      },
      can: ({
        owner,
        guest,
        public_link,
        team_viewer,
        review_group,
        active,
        banned,
      }) => ({
        view: anyOf(
          owner,
          guest,
          public_link,
          team_viewer,
          every(review_group).view,
        ),
        publish: allOf(owner, active).unless(banned),
        approve: owner.and(every(review_group).approve),
      }),
    });

    const dslModel = compileAccess([doc]);
    const dslZed = emitZed(dslModel);

    // Build the exact same schema using legacy hand-written access() API to prove IR parity.
    const UserH = entityHandle({
      wireName: "user",
      idSchema: z.string().min(1),
    });
    const TeamH = entityHandle({
      wireName: "team",
      idSchema: z.string().min(1),
    });
    const GroupH = entityHandle({
      wireName: "review_group",
      idSchema: z.string().min(1),
    });
    const DocH = entityHandle({ wireName: "doc", idSchema: z.string().min(1) });

    const manualUser = access(UserH, { roles: {}, permissions: () => ({}) });
    const manualTeam = access(TeamH, {
      roles: { member: UserH },
      permissions: (r) => ({ view: [r.member] }),
    });
    const manualGroup = access(GroupH, {
      roles: { reviewer: UserH },
      permissions: (r) => ({ view: [r.reviewer], approve: [r.reviewer] }),
    });
    const manualDoc = access(DocH, {
      roles: {
        owner: UserH,
        guest: withExpiration(UserH),
        public_link: wildcard(UserH),
        team_viewer: membersOf(manualTeam.roles.member),
        review_group: GroupH,
        active: wildcard(UserH),
        banned: UserH,
      },
      permissions: (r) => ({
        view: [
          r.owner,
          r.guest,
          r.public_link,
          r.team_viewer,
          throughAll(r.review_group, manualGroup.permissions.view),
        ],
        publish: [excluding(both(r.owner, r.active), r.banned)],
        approve: [
          both(
            r.owner,
            throughAll(r.review_group, manualGroup.permissions.approve),
          ),
        ],
      }),
    });
    const manualModel = accessModel([
      manualUser,
      manualTeam,
      manualGroup,
      manualDoc,
    ]);

    expect(
      accessIrDefinitionsDiff(
        emitAccessIr(dslModel),
        emitAccessIr(manualModel),
      ),
    ).toEqual([]);
    expect(dslZed).toContain("use expiration");
    expect(dslZed).toContain("relation guest: user with expiration");
    expect(dslZed).toContain("relation public_link: user:*");
    expect(dslZed).toContain("relation team_viewer: team#member");
    expect(dslZed).toContain("review_group.all(view)");
    expect(dslZed).toContain("review_group.all(approve)");
    expect(
      accessIrDefinitionsDiff(emitAccessIr(dslModel), parseZed(dslZed)),
    ).toEqual([]);
  });

  it("resolves cyclic lazy thunk role references without TDZ or infinite recursion", () => {
    const user = actor("user");

    type BetaResource = DslResource<
      "beta",
      {
        readonly owner: ActorRef<"user">;
        readonly linked_alpha: ResourceSubjectRef<"alpha">;
      },
      "view"
    >;

    const alpha = resource("alpha", {
      roles: {
        owner: user,
        linked_beta: (): BetaResource => beta,
      },
      can: ({ owner, linked_beta }) => ({
        view: anyOf(owner, linked_beta.view),
      }),
    });

    const beta: BetaResource = resource("beta", {
      roles: {
        owner: user,
        linked_alpha: () => alpha,
      },
      can: ({ owner, linked_alpha }) => ({
        view: [owner, linked_alpha.view],
      }),
    });

    const model = compileAccess([alpha]);
    const zed = emitZed(model);
    expect(zed).toContain("relation linked_beta: beta");
    expect(zed).toContain("relation linked_alpha: alpha");
    expect(zed).toContain("permission view = owner + linked_beta->view");
    expect(zed).toContain("permission view = owner + linked_alpha->view");
  });
});
