/** Tests the writer's ownership check before replacing a Zed fragment. */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { GENERATED_ZED_HEADER } from "./generated-header.js";
import type { AccessIrDefinition } from "./ir.js";
import { writeAccessArtifacts } from "./write-artifacts.js";

const FRAGMENT = "workspaces.zed";

const definitions: readonly AccessIrDefinition[] = [
  { wireName: "test/workspace", roles: [], permissions: [] },
  { wireName: "test/scale", roles: [], permissions: [] },
];

const targets = [{ relativePath: FRAGMENT, wireNames: ["test/workspace"] }];

describe("writeAccessArtifacts", () => {
  let repoRoot: string;

  beforeEach(() => {
    repoRoot = mkdtempSync(join(tmpdir(), "access-artifacts-"));
  });

  afterEach(() => {
    rmSync(repoRoot, { recursive: true, force: true });
  });

  function existingFragment(contents: string): void {
    writeFileSync(join(repoRoot, FRAGMENT), contents);
  }

  function regenerate(): readonly string[] {
    return writeAccessArtifacts({ repoRoot, definitions, targets });
  }

  it("overwrites a fragment carrying the current header", () => {
    existingFragment(`${GENERATED_ZED_HEADER}\n\ndefinition test/stale {}\n`);

    regenerate();

    expect(readFileSync(join(repoRoot, FRAGMENT), "utf8")).toBe(
      `${GENERATED_ZED_HEADER}\n\ndefinition test/workspace {}\n`,
    );
  });

  it.each(["// GENERATED by another kit — do not edit", `${GENERATED_ZED_HEADER} here`])(
    "refuses an unrecognized banner and preserves the file",
    (banner) => {
      const original = `${banner}\n\ndefinition test/workspace {}\n`;
      existingFragment(original);

      expect(() => regenerate()).toThrow(/hand-written/);
      expect(readFileSync(join(repoRoot, FRAGMENT), "utf8")).toBe(original);
    },
  );

  it("refuses a hand-written fragment", () => {
    const handWritten = "definition test/workspace {}\n";
    existingFragment(handWritten);

    expect(() => regenerate()).toThrow(/hand-written/);
    expect(readFileSync(join(repoRoot, FRAGMENT), "utf8")).toBe(handWritten);
  });

  it("writes a fragment that does not exist yet, holding only the names it claims", () => {
    expect(regenerate()).toEqual([join(repoRoot, FRAGMENT)]);
    expect(readFileSync(join(repoRoot, FRAGMENT), "utf8")).toBe(
      `${GENERATED_ZED_HEADER}\n\ndefinition test/workspace {}\n`,
    );
  });

  it("refuses a target naming a definition nobody registered", () => {
    expect(() =>
      writeAccessArtifacts({
        repoRoot,
        definitions,
        targets: [{ relativePath: FRAGMENT, wireNames: ["test/absent"] }],
      }),
    ).toThrow(/no access\(\) definition registered for test\/absent/);
  });
});
