/**
 * Banners and the one hand edit a generated table module allows.
 *
 * A brand is the fact the database cannot report, so adding or changing one —
 * with the import it needs — is not a hand edit. Everything around it is: a
 * column added, a brand taken away, an import nothing uses. The banners are
 * matched by shape, so a renamed kit banner is still recognised and a file
 * that merely mentions generation is not.
 */

import { describe, expect, it } from "vitest";
import { isAccessKitArtifact, isBrandOnlyEdit, isGeneratedTableModule } from "./generated-artifacts.js";

const HEADER = "// GENERATED - DO NOT EDIT\n";
const IMPORT = 'import { pgTable, text } from "drizzle-orm/pg-core";\n';
const BRAND_IMPORT = 'import type { OrderId } from "./order-id.js";\n';

function table(imports: string, columns: string): string {
  return `${HEADER}${imports}\nexport const orders = pgTable("orders", {\n${columns}});\n`;
}

const PLAIN = table(IMPORT, '  id: text("id"),\n');
const BRANDED = table(IMPORT + BRAND_IMPORT, '  id: text("id").$type<OrderId>(),\n');

describe("generated artifacts", () => {
  it("recognises each banner by its first line", () => {
    expect(isGeneratedTableModule(PLAIN)).toBe(true);
    expect(isGeneratedTableModule(`// a table\n${PLAIN}`)).toBe(false);
    expect(isAccessKitArtifact("// GENERATED by the access kit — do not edit\n")).toBe(true);
    expect(isAccessKitArtifact("// GENERATED by another kit — do not edit\nx\n")).toBe(false);
    expect(isAccessKitArtifact("// GENERATED by the tokens script from\n")).toBe(false);
  });

  it("allows a brand added with the import it needs", () => {
    expect(isBrandOnlyEdit(PLAIN, BRANDED)).toBe(true);
    expect(isBrandOnlyEdit(PLAIN, PLAIN)).toBe(true);
  });

  it("refuses every other change", () => {
    const added = table(IMPORT, '  id: text("id"),\n  note: text("note"),\n');
    const unused = table(IMPORT + BRAND_IMPORT, '  id: text("id"),\n');
    expect(isBrandOnlyEdit(PLAIN, added)).toBe(false);
    expect(isBrandOnlyEdit(BRANDED, PLAIN)).toBe(false);
    expect(isBrandOnlyEdit(PLAIN, unused)).toBe(false);
  });
});
