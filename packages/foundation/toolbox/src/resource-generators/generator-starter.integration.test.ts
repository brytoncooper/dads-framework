import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";

import { generateProjectArtifact } from "../cli-generator-commands.js";
import { renderStarterProjectFiles } from "../starter-project/render-starter-project.js";
import { parseGeneratorArguments } from "./generator-arguments.js";

const workspace = fileURLToPath(new URL("../../../../../", import.meta.url));
const nodeModules = join(workspace, "node_modules");
const commands = [
  ["domain", "inventory"],
  ["endpoint", "status", "--domain", "inventory", "--api", "staff"],
  ["table", "warehouse", "--domain", "inventory"],
  ["access", "warehouse", "--domain", "inventory"],
  ["flag", "batch", "--domain", "inventory"],
  ["email", "notice", "--domain", "inventory"],
  ["page", "overview", "--domain", "inventory"],
  ["resource", "catalog", "--api", "customer"],
];

function writeStarter(scratch: string) {
  for (const file of renderStarterProjectFiles({
    projectName: "generator-conformance",
  })) {
    const path = join(scratch, file.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.content);
  }
  symlinkSync(nodeModules, join(scratch, "node_modules"), "junction");
}

function runTool(scratch: string, executable: string, args: readonly string[]) {
  return execFileSync(process.execPath, [join(nodeModules, executable), ...args], {
    cwd: scratch,
    encoding: "utf8",
    timeout: 60_000,
  });
}

it("typechecks and runs all artifacts on an app generated by the kit starter", { timeout: 120_000 }, () => {
  const scratch = mkdtempSync(join(tmpdir(), "dads-generator-starter-"));
  try {
    writeStarter(scratch);
    for (const args of commands) {
      expect(generateProjectArtifact(scratch, parseGeneratorArguments(args)).files.length).toBeGreaterThan(0);
    }

    runTool(scratch, "typescript/bin/tsc", ["-p", "tsconfig.json", "--noEmit"]);
    const tests = runTool(scratch, "vitest/vitest.mjs", ["run", "--reporter=verbose", "domains", "tests"]);
    expect(tests).toContain("catalog-resource.test.ts");
    expect(tests).toContain("starter.integration.test.ts");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
});
