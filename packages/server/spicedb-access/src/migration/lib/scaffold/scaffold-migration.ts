import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { classifySchemaDiff, type SchemaDiffClassification } from "../logic/classify-schema-diff.js";

export type ScaffoldMigrationInput = {
  journalFolder: string;
  /** The freshly composed fragments (`npm run authz:generate` output). */
  composedSchema: string;
  /** For "new": lowercase words joined by underscores, e.g. "editors_become_owners". */
  slug?: string;
  /**
   * "new" appends the next numbered entry. "rebaseline" rewrites the latest
   * entry's snapshot in place — the PRE-DEPLOYMENT shortcut;
   * the caller refuses it once the deployment status says DEPLOYED.
   */
  mode: "new" | "rebaseline";
};

export type ScaffoldMigrationResult =
  | {
      readonly action: "created";
      readonly id: string;
      readonly classification: SchemaDiffClassification;
    }
  | { readonly action: "rebaselined"; readonly id: string }
  | { readonly action: "up-to-date"; readonly id: string };

const SLUG_PATTERN = /^[a-z0-9]+(?:_[a-z0-9]+)*$/;

/**
 * Mints a journal entry from the composed schema: snapshot + migration.ts
 * (a refuse-to-run TODO step when the diff is destructive) and regenerates
 * the journal index. Idempotent: an unchanged schema scaffolds nothing.
 */
export async function scaffoldMigration(input: ScaffoldMigrationInput): Promise<ScaffoldMigrationResult> {
  const entries = await listEntryIds(input.journalFolder);
  const latest = entries.at(-1);
  const latestSchema =
    latest === undefined ? "" : await readFile(join(input.journalFolder, latest, "schema.zed"), "utf8");

  if (latest !== undefined && latestSchema === input.composedSchema) {
    return { action: "up-to-date", id: latest };
  }

  if (input.mode === "rebaseline") {
    return rebaselineLatest(input, latest);
  }

  return createEntry(input, entries, latestSchema);
}

async function rebaselineLatest(
  input: ScaffoldMigrationInput,
  latest: string | undefined,
): Promise<ScaffoldMigrationResult> {
  if (latest === undefined) {
    throw new Error("nothing to rebaseline: the journal has no entries — scaffold a new one");
  }
  await writeFile(join(input.journalFolder, latest, "schema.zed"), input.composedSchema);
  return { action: "rebaselined", id: latest };
}

async function createEntry(
  input: ScaffoldMigrationInput,
  entries: readonly string[],
  latestSchema: string,
): Promise<ScaffoldMigrationResult> {
  const slug = input.slug;
  if (slug === undefined || !SLUG_PATTERN.test(slug)) {
    throw new Error(`a new migration needs a slug of lowercase words joined by underscores, got "${slug ?? ""}"`);
  }

  const classification = classifySchemaDiff(latestSchema, input.composedSchema);
  const id = `${String(entries.length + 1).padStart(4, "0")}_${slug}`;
  const entryFolder = join(input.journalFolder, id);

  await mkdir(entryFolder);
  await writeFile(join(entryFolder, "schema.zed"), input.composedSchema);
  await writeFile(join(entryFolder, "migration.ts"), migrationFileContent(id, classification));
  await writeFile(join(input.journalFolder, "index.ts"), journalIndexContent([...entries, id]));

  return { action: "created", id, classification };
}

function migrationFileContent(id: string, classification: SchemaDiffClassification): string {
  const header = `import type { AuthorizationMigration } from "../../index.js";\n\n`;

  if (classification.kind === "additive") {
    return (
      header +
      `/** Additive schema change — the snapshot writes without relationship work. */\n` +
      `export const migration: AuthorizationMigration = {\n` +
      `  id: "${id}",\n` +
      `};\n`
    );
  }

  const removalLines = classification.removals.map((removal) => ` *   - ${removal}`).join("\n");
  return (
    header +
    `/**\n` +
    ` * DESTRUCTIVE — this snapshot removes:\n` +
    `${removalLines}\n` +
    ` * Replace the throw with the relationship steps that preserve access\n` +
    ` * (backfill/move first, then delete the old relationships) so the schema\n` +
    ` * write becomes legal. The runner and the detector refuse this\n` +
    ` * entry until the TODO is gone.\n` +
    ` */\n` +
    `export const migration: AuthorizationMigration = {\n` +
    `  id: "${id}",\n` +
    `  beforeSchemaWrite: () => {\n` +
    `    throw new Error(\n` +
    `      "TODO(${id}): write the relationship steps for: ${classification.removals.join("; ")}",\n` +
    `    );\n` +
    `  },\n` +
    `};\n`
  );
}

function journalIndexContent(entryIds: readonly string[]): string {
  const imports = entryIds.map((id) => `import { migration as m${id} } from "./${id}/migration";`).join("\n");
  const list = entryIds.map((id) => `m${id}`).join(", ");
  return (
    `// GENERATED by \`npm run authz:migration:new\` — edit each entry's\n` +
    `// migration.ts, never this list. The runner refuses gaps, duplicates,\n` +
    `// and folders missing from it.\n` +
    `import type { AuthorizationMigration } from "../../index.js";\n` +
    `${imports}\n\n` +
    `export const journal: readonly AuthorizationMigration[] = [${list}];\n`
  );
}

async function listEntryIds(journalFolder: string): Promise<readonly string[]> {
  const entries = await readdir(journalFolder, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => /^\d{4}_/.test(name))
    .sort();
}
