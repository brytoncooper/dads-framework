import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";

const source = fileURLToPath(
  new URL("../../apps/kit-workbench/", import.meta.url),
);
const output = new URL(
  "../../packages/foundation/toolbox/src/starter-project/kit-starter.generated.ts",
  import.meta.url,
);

function sourceFiles(directory) {
  return readdirSync(join(source, directory), { withFileTypes: true }).flatMap(
    (entry) => {
      const name = directory === "" ? entry.name : `${directory}/${entry.name}`;
      return entry.isDirectory() ? sourceFiles(name) : [name];
    },
  );
}

const claudeImport = readFileSync(join(source, "CLAUDE.md"), "utf8");
if (claudeImport.trim() !== "@AGENTS.md") {
  throw new Error("CLAUDE.md must import the shared AGENTS.md instructions.");
}

const paths = [
  ".gitignore",
  ...sourceFiles(".agents/skills"),
  "AGENTS.md",
  "CLAUDE.md",
  "DEPLOY.md",
  "README.md",
  "dads.project.json",
  "package.json",
  "tsconfig.json",
  "index.html",
  "examples.html",
  "vite.config.ts",
  ...[
    "apps",
    "assembly",
    "domains",
    "examples",
    "libraries",
    "migrations",
    "tests",
  ].flatMap(sourceFiles),
].sort();

const generated = [
  "// Generated by scripts/build/sync-kit-starter.mjs.",
  "// prettier-ignore",
  "export const kitStarterFiles = [",
  ...paths.map(
    (name) =>
      `  { path: ${JSON.stringify(name)}, content: ${JSON.stringify(readFileSync(join(source, name), "utf8"))} },`,
  ),
  "];",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated) {
    throw new Error(
      "The kit starter changed. Run node scripts/build/sync-kit-starter.mjs.",
    );
  }
} else {
  writeFileSync(output, generated);
}
